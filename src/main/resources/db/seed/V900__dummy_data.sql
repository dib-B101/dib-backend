-- 경매 집계 vs 입찰
SELECT a.auction_id FROM auction a
 WHERE a.auction_id >= 4 AND (
       a.bid_count <> (SELECT COUNT(*) FROM bid b WHERE b.auction_id = a.auction_id)
    OR a.bidder_count <> (SELECT COUNT(DISTINCT member_id) FROM bid b WHERE b.auction_id = a.auction_id)
    OR a.current_price <> COALESCE((SELECT MAX(amount) FROM bid b WHERE b.auction_id = a.auction_id), a.start_price)
    OR (a.top_bid_id IS NULL) <> NOT EXISTS (SELECT 1 FROM bid b WHERE b.auction_id = a.auction_id)
    OR (a.top_bid_id IS NOT NULL AND a.top_bid_id <> (SELECT bid_id FROM bid b WHERE b.auction_id = a.auction_id ORDER BY amount DESC LIMIT 1))
 );

